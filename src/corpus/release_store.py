def active(conn, shard_key):
    with conn.cursor() as cur:
        cur.execute("SELECT * FROM corpus_release_active WHERE shard_key=%s", (shard_key,))
        return cur.fetchone()


def active_set(conn):
    """The whole fleet's active releases, read in ONE statement.

    One statement is one MVCC snapshot. Because activation is one transaction, a reader here can
    never see half of a switch, which is the property that keeps a query inside one generation.
    """
    with conn.cursor() as cur:
        cur.execute("SELECT shard_key, release_id, previous_release_id, generation, activated_at "
                    "FROM corpus_release_active ORDER BY shard_key")
        return {r["shard_key"]: r for r in cur.fetchall()}


def _gate(conn, new_row, prev_release_id, force):
    """Refuse a release whose completeness went backwards. `force` records the override rather
    than hiding it."""
    from corpus import stats as stats_mod          # local: stats imports nothing from here
    if force or not prev_release_id:
        return []
    prev = get(conn, prev_release_id)
    cmp = stats_mod.compare(dict((prev or {}).get("stats") or {}),
                            dict(new_row.get("stats") or {}))
    if cmp["regressions"]:
        raise StatsRegression(
            f"{new_row['release_id']} is worse than {prev_release_id}: "
            + "; ".join(c["detail"] for c in cmp["regressions"]), cmp["regressions"])
    return cmp["regressions"]


def activate(conn, release_id, *, actor="", reason="", force=False, commit=True):
    """Switch one shard key over. One transaction, gated, reversible."""
    return activate_many(conn, [release_id], actor=actor, reason=reason, force=force,
                         commit=commit)


def activate_many(conn, release_ids, *, actor="", reason="", force=False, commit=True):
    """Switch several shard keys over in ONE transaction.

    This is the multi-shard case the fan-out cares about: a search asks the hot shard and two
    domain shards, and if those three switched in three transactions there is a window in which
    the answer is assembled from two generations of the corpus. There is no such window here.

    `commit=False` leaves the transaction open, which is how the test proves that a concurrent
    reader sees none of it until the commit.
    """
    if conn.autocommit:
        raise ReleaseError("activation needs a transactional connection; autocommit is on")
    done = []
    with conn.cursor() as cur:
        cur.execute("SELECT nextval('corpus_release_generation_seq') g")
        generation = int(cur.fetchone()["g"])
        for release_id in release_ids:
            cur.execute("SELECT * FROM corpus_release WHERE release_id=%s FOR UPDATE",
                        (release_id,))
            rel = cur.fetchone()
            if not rel:
                raise ReleaseError(f"no such release: {release_id}")
            if rel["sealed_at"] is None:
                raise NotSealed(f"release {release_id} is not sealed and cannot be activated")
            if rel["state"] not in ACTIVATABLE_STATES and rel["state"] != "active":
                raise ReleaseError(f"release {release_id} is {rel['state']}, not activatable")

            cur.execute("SELECT * FROM corpus_release_active WHERE shard_key=%s FOR UPDATE",
                        (rel["shard_key"],))
            cur_active = cur.fetchone()
            prev_id = cur_active["release_id"] if cur_active else None
            if prev_id == release_id:
                done.append({"shard_key": rel["shard_key"], "release_id": release_id,
                             "generation": cur_active["generation"], "unchanged": True})
                continue
            _gate(conn, rel, prev_id, force)

            cur.execute("""INSERT INTO corpus_release_active (shard_key, release_id,
                               previous_release_id, generation, activated_at, activated_by, reason)
                           VALUES (%s,%s,%s,%s, now(), %s, %s)
                           ON CONFLICT (shard_key) DO UPDATE SET
                               release_id = EXCLUDED.release_id,
                               previous_release_id = EXCLUDED.previous_release_id,
                               generation = EXCLUDED.generation,
                               activated_at = EXCLUDED.activated_at,
                               activated_by = EXCLUDED.activated_by,
                               reason = EXCLUDED.reason
                           RETURNING *""",
                        (rel["shard_key"], release_id, prev_id, generation, actor,
                         reason + (" [forced]" if force else "")))
            row = cur.fetchone()
            cur.execute("UPDATE corpus_release SET state='active' WHERE release_id=%s",
                        (release_id,))
            if prev_id:
                cur.execute("UPDATE corpus_release SET state='superseded' WHERE release_id=%s",
                            (prev_id,))
            done.append({"shard_key": row["shard_key"], "release_id": row["release_id"],
                         "previous_release_id": row["previous_release_id"],
                         "generation": row["generation"], "unchanged": False})
    if commit:
        conn.commit()
    return {"generation": generation, "activated": done}


def rollback(conn, shard_key, *, actor="", reason="", commit=True):
    """Return a shard key to the release it was serving before, in one transaction.

    The pair is SWAPPED, not popped: `previous_release_id` becomes the release being rolled back
    from. So a rollback is itself reversible, and an operator who rolls back the wrong shard can
    undo it with the same call rather than needing a build.
    """
    if conn.autocommit:
        raise ReleaseError("rollback needs a transactional connection; autocommit is on")
    with conn.cursor() as cur:
        cur.execute("SELECT * FROM corpus_release_active WHERE shard_key=%s FOR UPDATE",
                    (shard_key,))
        row = cur.fetchone()
        if not row:
            raise ReleaseError(f"{shard_key} has no active release")
        if not row["previous_release_id"]:
            raise ReleaseError(f"{shard_key} has no previous release to roll back to")
        cur.execute("SELECT nextval('corpus_release_generation_seq') g")
        generation = int(cur.fetchone()["g"])
        from_id, to_id = row["release_id"], row["previous_release_id"]
        cur.execute("""UPDATE corpus_release_active SET release_id=%s, previous_release_id=%s,
                           generation=%s, activated_at=now(), activated_by=%s, reason=%s
                       WHERE shard_key=%s RETURNING *""",
                    (to_id, from_id, generation, actor,
                     reason or f"rollback from {from_id}", shard_key))
        out = cur.fetchone()
        cur.execute("UPDATE corpus_release SET state='active' WHERE release_id=%s", (to_id,))
        cur.execute("UPDATE corpus_release SET state='superseded' WHERE release_id=%s", (from_id,))
    if commit:
        conn.commit()
    return {"shard_key": shard_key, "release_id": to_id, "previous_release_id": from_id,
            "generation": out["generation"], "rolled_back_from": from_id}


