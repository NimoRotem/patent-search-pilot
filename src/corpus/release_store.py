"""Reading and writing the release tables, and the one transaction that switches a shard over.

ACTIVATION IS THE ONLY MOMENT THIS SYSTEM CHANGES WHAT IT SEARCHES. Everything else here is
bookkeeping. So the rules are narrow and they are enforced, not documented:

    * a release must be SEALED before it can be activated. A sealed release is immutable in the
      database (sql/010 trigger), so what gets activated cannot be edited afterwards;
    * activation is ONE transaction covering every shard key it touches, so a reader either sees
      the whole new generation or the whole old one. A query cannot fan out across two
      generations, because there is no instant at which two generations are both visible;
    * activation is gated on the release's completeness statistics against the release it
      replaces. A release that is worse than its predecessor is refused before it serves, not
      discovered afterwards;
    * rollback SWAPS the pair. Rolling back sets active to the previous release and previous to
      the one you left, so rolling back a rollback returns to where you were, and the switch is
      reversible in both directions rather than one.
"""
from __future__ import annotations

import json
import os

import psycopg
from psycopg.rows import dict_row

#  The builder never connects to production by default. `config.PG_DSN` is the live corpus; a
#  release database is a separate DSN that has to be named on purpose.
RELEASE_DSN_ENV = "CORPUS_RELEASE_DSN"

SEALABLE_STATES = ("building", "built")
ACTIVATABLE_STATES = ("built", "verified", "superseded")


class ReleaseError(RuntimeError):
    pass


class NotSealed(ReleaseError):
    pass


class StatsRegression(ReleaseError):
    """Raised instead of activating a release whose completeness went backwards."""

    def __init__(self, message, regressions):
        super().__init__(message)
        self.regressions = list(regressions or [])


def dsn(explicit=None):
    d = explicit or os.environ.get(RELEASE_DSN_ENV) or ""
    if not d:
        raise ReleaseError(
            f"no release DSN: set {RELEASE_DSN_ENV}. There is deliberately no default, because a "
            f"default that happens to be the production corpus is how an offline builder builds "
            f"an HNSW index on the live database.")
    return d


def connect(explicit=None, autocommit=False):
    return psycopg.connect(dsn(explicit), row_factory=dict_row, autocommit=autocommit)


def _j(v):
    return json.dumps(v or {}, default=str)


