def observed_counts(conn, release_id):
    with conn.cursor() as cur:
        cur.execute('SELECT count(*) n FROM chunks_release WHERE release_id=%s', (release_id,))
        chunks = int(cur.fetchone()["n"])
        cur.execute("SELECT count(*) n FROM corpus_release_member WHERE release_id=%s",
                    (release_id,))
        fams = int(cur.fetchone()["n"])
        cur.execute("SELECT count(DISTINCT publication_id) n FROM chunks_release WHERE release_id=%s",
                    (release_id,))
        pubs = int(cur.fetchone()["n"])
    return {"chunks": chunks, "families": fams, "publications": pubs}


def verify_serving(conn, release_id, *, artifact_root=None):
    """"Am I serving the release I think I am?"

    Recomputes the manifest hash, rechecks every artifact on disk, recounts the rows and rereads
    the index definition. A shard that cannot answer yes must not join the fan-out: a stale shard
    does not fail a search, it silently answers from an older corpus, which is the failure mode
    nobody notices.
    """
    from corpus import manifest as manifest_mod
    rel = get(conn, release_id)
    if not rel:
        v = manifest_mod.Verification()
        return v.add("release_present", False, f"no row for {release_id}")
    m = rel["manifest"] or {}
    v = manifest_mod.verify(m, artifact_root=artifact_root,
                            observed_counts=observed_counts(conn, release_id),
                            observed_index_params=observed_index_params(conn, release_id))
    v.add("sealed", rel["sealed_at"] is not None, f"state={rel['state']}")
    v.add("content_hash_recorded", bool(rel["content_hash"])
          and rel["content_hash"] == m.get("content_hash"),
          f"row {rel['content_hash']} != manifest {m.get('content_hash')}")
    return v
