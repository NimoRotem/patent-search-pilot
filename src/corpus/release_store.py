def next_version(conn, shard_key):
    with conn.cursor() as cur:
        cur.execute("SELECT COALESCE(max(version), 0) + 1 v FROM corpus_release WHERE shard_key=%s",
                    (shard_key,))
        return int(cur.fetchone()["v"])


def release_id_for(shard_key, version):
    return f"{shard_key}_v{int(version)}"


def create(conn, *, shard_key, version=None, kind="domain", builder="", note=""):
    """Open a new release for building. State `building`, not sealed, no content hash yet."""
    version = int(version or next_version(conn, shard_key))
    rid = release_id_for(shard_key, version)
    with conn.cursor() as cur:
        cur.execute("""INSERT INTO corpus_release (release_id, shard_key, version, kind, state,
                                                   builder, note)
                       VALUES (%s,%s,%s,%s,'building',%s,%s) RETURNING *""",
                    (rid, shard_key, version, kind, builder, note))
        return cur.fetchone()


def ensure_partition(conn, release_id):
    """One partition per release. This is what makes immutability physical: a release is built
    into its own heap, indexed once, and retired by DETACH rather than by a DELETE that would
    rewrite the HNSW graph of every other release sharing the table."""
    name = partition_name(release_id)
    with conn.cursor() as cur:
        cur.execute("SELECT to_regclass(%s) t", (name,))
        if cur.fetchone()["t"] is not None:
            return name
        #  release_id is generated by `release_id_for` from a shard key this module owns; it is
        #  still validated here, because an identifier reaching DDL by string interpolation is
        #  worth one explicit check rather than an assumption about every caller.
        if not _safe_ident(release_id):
            raise ReleaseError(f"unsafe release_id for a partition name: {release_id!r}")
        #  `FOR VALUES IN` takes a literal, not a parameter: Postgres cannot infer the type of a
        #  bind parameter in partition bound DDL. `_safe_ident` above is what makes the literal
        #  safe, which is why it is checked rather than assumed.
        cur.execute(f'CREATE TABLE "{name}" PARTITION OF chunks_release '
                    f"FOR VALUES IN ('{release_id}')")
    return name


def partition_name(release_id):
    return f"chunks_release_{release_id}"


def _safe_ident(s):
    s = str(s or "")
    return bool(s) and len(s) <= 48 and all(c.isalnum() or c == "_" for c in s) and not s[0].isdigit()


def build_indexes(conn, release_id, *, m=16, ef_construction=64, halfvec=False,
                  maintenance_work_mem=None, parallel_workers=None):
    """The dense index, built on the release's own partition, offline.

    NEVER run this against a serving database. pgvector holds the whole graph in
    `maintenance_work_mem` and falls back to a much slower two-phase on-disk build when it does
    not fit, so the builder box has to be at least as large as the shard it is building for. See
    `corpus.sizing.build_ram_required_gib`.
    """
    part = partition_name(release_id)
    if not _safe_ident(release_id):
        raise ReleaseError(f"unsafe release_id: {release_id!r}")
    col = "embedding::halfvec(768)" if halfvec else "embedding"
    opclass = "halfvec_cosine_ops" if halfvec else "vector_cosine_ops"
    params = {"type": "hnsw", "opclass": opclass, "m": int(m),
              "ef_construction": int(ef_construction), "dim": 768,
              "halfvec": bool(halfvec)}
    with conn.cursor() as cur:
        if maintenance_work_mem:
            cur.execute(f"SET maintenance_work_mem = '{maintenance_work_mem}'")
        if parallel_workers is not None:
            cur.execute(f"SET max_parallel_maintenance_workers = {int(parallel_workers)}")
        cur.execute(f'CREATE INDEX IF NOT EXISTS "ix_{part}_hnsw" ON "{part}" '
                    f'USING hnsw (({col}) {opclass}) '
                    f'WITH (m = {int(m)}, ef_construction = {int(ef_construction)})')
        cur.execute(f'CREATE INDEX IF NOT EXISTS "ix_{part}_family" ON "{part}" (family_key)')
        cur.execute(f'CREATE INDEX IF NOT EXISTS "ix_{part}_pub" ON "{part}" (publication_id)')
        cur.execute(f'CREATE INDEX IF NOT EXISTS "ix_{part}_kind" ON "{part}" (kind)')
        cur.execute(f'ANALYZE "{part}"')
    return params


def observed_index_params(conn, release_id):
    """What the database actually reports for this release's dense index, for `manifest.verify`."""
    part = partition_name(release_id)
    with conn.cursor() as cur:
        cur.execute("SELECT indexdef FROM pg_indexes WHERE indexname = %s", (f"ix_{part}_hnsw",))
        row = cur.fetchone()
    if not row:
        return {}
    d = row["indexdef"]
    out = {"type": "hnsw", "dim": 768,
           "opclass": "halfvec_cosine_ops" if "halfvec_cosine_ops" in d else "vector_cosine_ops",
           "halfvec": "halfvec" in d}
    for key in ("m", "ef_construction"):
        marker = f"{key}='"
        if marker in d:
            out[key] = int(d.split(marker, 1)[1].split("'", 1)[0])
    return out


def index_bytes(conn, release_id):
    part = partition_name(release_id)
    with conn.cursor() as cur:
        cur.execute("SELECT COALESCE(pg_indexes_size(to_regclass(%s)), 0) idx, "
                    "COALESCE(pg_total_relation_size(to_regclass(%s)), 0) total", (part, part))
        r = cur.fetchone()
    return {"index_bytes": int(r["idx"]), "total_bytes": int(r["total"])}


def add_members(conn, release_id, rows):
    """rows: dicts with family_key, home_domain, secondary_domains, n_publications, n_chunks."""
    if not rows:
        return 0
    with conn.cursor() as cur:
        with cur.copy("COPY corpus_release_member (release_id, family_key, home_domain, "
                      "secondary_domains, n_publications, n_chunks, source) FROM STDIN") as cp:
            for r in rows:
                cp.write_row((release_id, r["family_key"], r["home_domain"],
                              list(r.get("secondary_domains") or []),
                              int(r.get("n_publications") or 0), int(r.get("n_chunks") or 0),
                              r.get("source") or "corpus"))
    return len(rows)


def set_shard_rows(conn, release_id, rows):
    if not rows:
        return 0
    with conn.cursor() as cur:
        for r in rows:
            cur.execute("""INSERT INTO corpus_release_shard (release_id, domain, n_families,
                               n_publications, n_chunks, index_bytes, disk_bytes)
                           VALUES (%s,%s,%s,%s,%s,%s,%s)
                           ON CONFLICT (release_id, domain) DO UPDATE SET
                               n_families=EXCLUDED.n_families,
                               n_publications=EXCLUDED.n_publications,
                               n_chunks=EXCLUDED.n_chunks,
                               index_bytes=EXCLUDED.index_bytes,
                               disk_bytes=EXCLUDED.disk_bytes""",
                        (release_id, r["domain"], int(r.get("n_families") or 0),
                         int(r.get("n_publications") or 0), int(r.get("n_chunks") or 0),
                         int(r.get("index_bytes") or 0), int(r.get("disk_bytes") or 0)))
    return len(rows)


def seal(conn, release_id, manifest, *, snapshot_path="", snapshot_sha256="", snapshot_bytes=0,
         state="built"):
    """Stamp the manifest and close the release for editing.

    After this the sql/010 trigger refuses every column but `state`, so the counts, the checksums
    and the index parameters a shard verifies against cannot drift from what was built.
    """
    with conn.cursor() as cur:
        cur.execute("SELECT state, sealed_at FROM corpus_release WHERE release_id=%s FOR UPDATE",
                    (release_id,))
        row = cur.fetchone()
        if not row:
            raise ReleaseError(f"no such release: {release_id}")
        if row["sealed_at"] is not None:
            raise ReleaseError(f"release {release_id} is already sealed")
        if row["state"] not in SEALABLE_STATES:
            raise ReleaseError(f"release {release_id} is {row['state']}, not sealable")
        cur.execute("""UPDATE corpus_release SET state=%s, content_hash=%s, manifest=%s,
                           built_from=%s, counts=%s, index_params=%s, stats=%s,
                           snapshot_path=%s, snapshot_sha256=%s, snapshot_bytes=%s,
                           built_at=COALESCE(built_at, now()), sealed_at=now()
                       WHERE release_id=%s RETURNING *""",
                    (state, manifest.get("content_hash", ""), _j(manifest),
                     _j(manifest.get("built_from")), _j(manifest.get("counts")),
                     _j(manifest.get("index_params")), _j(manifest.get("stats")),
                     snapshot_path, snapshot_sha256, int(snapshot_bytes), release_id))
        return cur.fetchone()


def get(conn, release_id):
    with conn.cursor() as cur:
        cur.execute("SELECT * FROM corpus_release WHERE release_id=%s", (release_id,))
        return cur.fetchone()


def members(conn, release_id, limit=None):
    with conn.cursor() as cur:
        cur.execute("SELECT * FROM corpus_release_member WHERE release_id=%s ORDER BY family_key"
                    + (" LIMIT %s" if limit else ""),
                    (release_id, limit) if limit else (release_id,))
        return cur.fetchall()


def shard_domains(conn, release_id):
    with conn.cursor() as cur:
        cur.execute("SELECT * FROM corpus_release_shard WHERE release_id=%s ORDER BY domain",
                    (release_id,))
        return cur.fetchall()


def releases_for_domain(conn, domain):
    """Which releases hold this domain. The domain -> shard lookup `shard_router.route()` feeds."""
    with conn.cursor() as cur:
        cur.execute("""SELECT s.release_id, r.shard_key, a.shard_key IS NOT NULL AS is_active
                       FROM corpus_release_shard s
                       JOIN corpus_release r ON r.release_id = s.release_id
                       LEFT JOIN corpus_release_active a ON a.release_id = s.release_id
                       WHERE s.domain = %s ORDER BY is_active DESC, r.shard_key""", (domain,))
        return cur.fetchall()


