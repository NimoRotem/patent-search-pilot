"""Make the legible copy in a 1.290 packet actually legible, and actually the document.

WHY THIS EXISTS. The audit blocked a finished packet over seven of its twenty documents and was
right to, but its diagnosis said "drawings bundle or an unsearchable scan" for all seven, and those
are three different defects with three different remedies. Looking at the seven:

    CN108748243A   18pp, no text layer      the WHOLE document, as an image scan
    CN108858267A   17pp, no text layer      the whole document, as an image scan
    SU1296407A1     3pp, no text layer      the whole document, as an image scan
    GB2211356A     12pp, watermarked        the whole document, with "Generated by PDFKit.NET
    FR2820352A1    35pp, watermarked        Evaluation" printed in red on EVERY page
    JPH08155874A    1pp, no text layer      ONE DRAWING SHEET. OPS holds 5 pages.
    DE650728C       1pp, no text layer      ONE DRAWING SHEET. OPS holds 4 pages.

Only the last two were what the audit said. So:

  AN IMAGE SCAN IS NOT A DEFECT, IT IS AN OCR JOB. A page-image facsimile of the whole
  specification is a legible copy under 1.290(d)(3); what it is not is SEARCHABLE, and that is why
  every quotation checked against it came back missing. OCR gives it a text layer, the quotations
  can then be verified against the paper that will actually be filed, and the examiner's copy is
  unchanged in appearance because the layer is invisible.

  A THIRD PARTY'S EVALUATION WATERMARK IS A DEFECT NOBODY HAD NAMED. Espacenet's whole-document
  download is rendered by an unlicensed PDFKit.NET, which stamps every page. Two copies in this
  packet carried it. It is not ours to strip from someone else's document, and it must not go to
  the Office, so the remedy is to obtain the copy from somewhere that does not stamp it: OPS
  returns the same facsimile as per-page TIFF/PDF which we stitch ourselves.

  A ONE-PAGE COPY OF A FIVE-PAGE PUBLICATION IS THE ORIGINAL SIN, and it had a root cause:
  `ops.fetch_facsimile` takes `insts[0]`, which OPS orders Drawing-first. That is right for the
  result-card figures it was written for and wrong for a filing copy, so the filing path asks for
  the FullDocument instance by name.

NOTHING HERE INVENTS TEXT. OCR reads what is on the page. Where it reads badly the quotation check
simply keeps failing, which is the honest outcome; it never edits a quotation to match, and it
never edits the image.
"""
from __future__ import annotations

import io
import json
import os
import re
import subprocess
import tempfile
import traceback

#  Producers that stamp their output. `PDFKit.NET 1.0.11` is the one seen in the wild, on the
#  Espacenet whole-document route; the others are here because the same class of licence banner
#  would be just as unfilable and costs nothing to look for.
_EVAL_PRODUCER = re.compile(
    r"(PDFKit\.NET|Aspose|iTextSharp\s+Trial|Spire\.|PDFtron\s+Demo|Debenu\s+Quick\s+PDF\s+Demo)",
    re.I)
#  The stamp as it lands in the text layer.
_EVAL_TEXT = re.compile(
    r"(Generated\s+by\s+PDFKit\.NET\s+Evaluation"
    r"|Evaluation\s+Only\.?\s*Created\s+with\s+Aspose"
    r"|Created\s+with\s+an?\s+(evaluation|trial)\s+(copy|version)"
    r"|This\s+document\s+was\s+created\s+with\s+an\s+unregistered)", re.I)

#  Tesseract language packs installed on this host, by issuing office. `eng` is always appended:
#  a foreign publication's front page carries English classification and INID data, and the
#  bilingual EP/WO members are common.
_OCR_LANG = {
    "CN": "chi_sim", "TW": "chi_sim", "JP": "jpn", "DE": "deu", "AT": "deu", "CH": "deu",
    "FR": "fra", "BE": "fra", "ES": "spa", "MX": "spa", "AR": "spa", "IT": "ita",
    "RU": "rus", "SU": "rus", "UA": "rus", "BY": "rus",
}
#  A page of a patent facsimile that OCRs to less than this has no prose on it. Deliberately low:
#  the question is "is there a specification in here at all", not "did OCR do well".
MIN_CHARS_PER_PAGE = 40
OCR_TIMEOUT = int(os.environ.get("COPY_OCR_TIMEOUT", "600"))


def ocr_lang(pub) -> str:
    code = str(pub or "").strip().upper()[:2]
    lang = _OCR_LANG.get(code)
    return ("%s+eng" % lang) if lang else "eng"


def _text_of(blob):
    """(pages, raw_text) from a PDF blob. Never raises."""
    try:
        from pypdf import PdfReader
        r = PdfReader(io.BytesIO(blob))
        return len(r.pages), " ".join((p.extract_text() or "") for p in r.pages)
    except Exception:                                                     # noqa: BLE001
        return 0, ""


def _producer(blob):
    try:
        from pypdf import PdfReader
        return str((PdfReader(io.BytesIO(blob)).metadata or {}).get("/Producer") or "")
    except Exception:                                                     # noqa: BLE001
        return ""


def assess(blob, pub=""):
    """What is wrong with this copy, if anything. -> dict

    `chars` EXCLUDES any evaluation stamp, which is the whole point: GB2211356A extracted 372
    characters and every one of them was the watermark, so a naive character count called it
    "has some text" while the document it is a copy of contributed nothing.
    """
    out = {"pages": 0, "chars": 0, "raw_chars": 0, "watermark": "", "producer": "",
           "searchable": False, "ok": False}
    if not blob:
        return out
    pages, text = _text_of(blob)
    out["pages"] = pages
    out["raw_chars"] = len("".join(text.split()))
    out["producer"] = _producer(blob)
    stamped = _EVAL_TEXT.search(text) or _EVAL_PRODUCER.search(out["producer"])
    if stamped:
        out["watermark"] = (stamped.group(0) if hasattr(stamped, "group") else "").strip()[:60]
    clean = _EVAL_TEXT.sub(" ", text)
    out["chars"] = len("".join(clean.split()))
    out["searchable"] = bool(pages) and out["chars"] >= MIN_CHARS_PER_PAGE * pages
    #  A copy is fit to file when it carries the document's own text and nobody else's banner.
    out["ok"] = out["searchable"] and not out["watermark"]
    return out


def ocr(blob, pub="", timeout=OCR_TIMEOUT):
    """Add a text layer to a page-image copy. -> (bytes, note). Returns the input on any failure.

    `--force-ocr` rather than `--skip-text`: the copies that need this most are the ones whose
    only existing text is an evaluation stamp, and skip-text would leave those exactly as they
    were. Forcing rasterises and re-lays the text over the same image, so what the examiner sees
    does not change.
    """
    if not blob:
        return blob, ""
    lang = ocr_lang(pub)
    with tempfile.TemporaryDirectory() as td:
        src, dst = os.path.join(td, "in.pdf"), os.path.join(td, "out.pdf")
        try:
            with open(src, "wb") as fh:
                fh.write(blob)
            r = subprocess.run(
                ["ocrmypdf", "-l", lang, "--force-ocr", "--optimize", "0",
                 "--output-type", "pdf", "-q", src, dst],
                capture_output=True, timeout=timeout)
            if r.returncode != 0 or not os.path.exists(dst) or os.path.getsize(dst) < 1024:
                return blob, ""
            got = open(dst, "rb").read()
        except Exception:                                                 # noqa: BLE001
            traceback.print_exc()
            return blob, ""
    before, after = assess(blob, pub), assess(got, pub)
    if after["chars"] <= before["chars"]:
        #  OCR that found nothing is not an improvement, and swapping in a rasterised copy for no
        #  gain would only lose whatever the original had.
        return blob, ""
    return got, ("read by OCR (%s): %d characters of text recovered from %d page image%s"
                 % (lang, after["chars"], after["pages"], "" if after["pages"] == 1 else "s"))


def full_document_facsimile(pub, max_pages=60, min_pages=0):
    """The FullDocument facsimile from EPO OPS, stitched here. -> (bytes, note) or (b"", "").

    NOT `ops.fetch_facsimile`, which takes the first instance OPS lists and OPS lists Drawing
    first. That is correct for the result-card figures it was written for and produces a one-page
    copy of a five-page publication for a filing, which is how DE650728C and JPH08155874A came to
    be filed as a single drawing sheet each.

    Stitched locally on purpose: it is also the way round Espacenet's whole-document download,
    which is rendered by an unlicensed PDFKit.NET and stamps every page.
    """
    try:
        import ops
    except Exception:                                                     # noqa: BLE001
        return b"", ""
    if not ops.have_creds():
        return b"", ""
    try:
        data = ops.ops_fetch(pub, want=("images",))
    except Exception:                                                     # noqa: BLE001
        return b"", ""
    insts = data.get("images") or []
    full = [i for i in insts if "full" in str(i.get("desc") or "").lower()]
    inst = (full or [i for i in insts if i.get("pages")] or insts or [None])[0]
    if not inst or not inst.get("link"):
        return b"", ""
    n = min(int(inst.get("pages") or 1) or 1, max_pages)
    #  DECIDE BEFORE PAYING. The instance list is one cheap call; the pages are one call each
    #  against a shared OPS budget. If OPS holds no more of this document than we already have,
    #  there is nothing here worth fetching and the copy we hold is as complete as it gets.
    if min_pages and n <= min_pages:
        return b"", ""
    pages = []
    for i in range(1, n + 1):
        try:
            b = ops.fetch_image_page(inst["link"], i)
        except Exception:                                                 # noqa: BLE001
            break
        if not b:
            break
        pages.append(b)
    if not pages:
        return b"", ""
    blob = _stitch(pages)
    if not blob:
        return b"", ""
    return blob, ("copy replaced with the %s facsimile from EPO OPS, %d page%s"
                  % (inst.get("desc") or "FullDocument", len(pages),
                     "" if len(pages) == 1 else "s"))


def _stitch(pages):
    """One PDF from the per-page PDFs OPS returns. -> bytes (b"" on failure)."""
    if not pages:
        return b""
    if len(pages) == 1:
        return pages[0]
    with tempfile.TemporaryDirectory() as td:
        parts = []
        for i, b in enumerate(pages):
            p = os.path.join(td, "p%03d.pdf" % i)
            with open(p, "wb") as fh:
                fh.write(b)
            parts.append(p)
        out = os.path.join(td, "out.pdf")
        try:
            r = subprocess.run(["pdfunite", *parts, out], capture_output=True, timeout=180)
            if r.returncode == 0 and os.path.exists(out) and os.path.getsize(out) > 0:
                return open(out, "rb").read()
        except Exception:                                                 # noqa: BLE001
            traceback.print_exc()
    return b""


#  REPAIRING A COPY IS EXPENSIVE AND THE ANSWER DOES NOT CHANGE. OCR is ~20 seconds a document
#  and a replacement is one OPS request per page against a budget shared with every other search on
#  this box. A packet gets rebuilt whenever somebody adds ten more documents to it, and without
#  this every rebuild paid the whole bill again for copies that were already fixed.
#
#  Keyed on the bytes that went IN, so a different source file for the same publication is a
#  different cache entry and a stale repair can never be served for a copy that has since changed.
CACHE = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                     "data", "copy_repair")


def _cache_key(pub, blob):
    import hashlib
    h = hashlib.sha1(blob).hexdigest()[:16]
    safe = re.sub(r"[^A-Za-z0-9]+", "", str(pub or "x"))[:40]
    return os.path.join(CACHE, "%s-%s" % (safe, h))


def _cache_get(pub, blob):
    base = _cache_key(pub, blob)
    try:
        with open(base + ".json") as fh:
            notes = json.load(fh)
        with open(base + ".pdf", "rb") as fh:
            got = fh.read()
        return (got, notes) if got[:5] == b"%PDF-" else None
    except Exception:                                                     # noqa: BLE001
        return None


def _cache_put(pub, blob, out, notes):
    base = _cache_key(pub, blob)
    try:
        os.makedirs(CACHE, exist_ok=True)
        with open(base + ".pdf", "wb") as fh:
            fh.write(out)
        with open(base + ".json", "w") as fh:
            json.dump(notes, fh)
    except Exception:                                                     # noqa: BLE001
        traceback.print_exc()


def repair(pub, blob, want_pages=0):
    """Return the best copy of `pub` we can produce, and what was done. -> (bytes, [note])

    The order is: keep what we have if it is already fit; otherwise get a cleaner rendition if the
    one we hold is stamped or is plainly a fragment; then OCR whatever we ended up with. Each step
    only replaces the copy when it MEASURES better, so a failed fetch or a bad OCR leaves the
    packet exactly as it was rather than making it worse.
    """
    notes = []
    best, cur = blob, assess(blob, pub)
    if cur["ok"]:
        return best, notes
    hit = _cache_get(pub, blob)
    if hit:
        return hit

    #  A stamped copy cannot be filed and cannot be cleaned; only replaced. A copy that is a
    #  fragment cannot be OCR'd into the rest of the document either. Both mean: go and get it
    #  again, from the route that does not stamp and does not truncate.
    #  ASK EVERY TIME THE COPY IS NOT FIT, not only when we already suspect a fragment.
    #  Nothing in a one-page PDF says it is page 5 of a 5-page publication: JPH08155874A and
    #  DE650728C looked exactly like complete single-sheet documents until OPS was asked how many
    #  pages the publication has. The ask is one metadata call, and `min_pages` makes it fetch
    #  nothing when OPS holds no more than we do.
    fragment = bool(want_pages) and cur["pages"] and cur["pages"] < want_pages
    if True:
        alt, note = full_document_facsimile(
            pub, min_pages=0 if (cur["watermark"] or fragment) else cur["pages"])
        if alt:
            a = assess(alt, pub)
            better = (a["pages"] > cur["pages"]) or (a["chars"] > cur["chars"]) or (
                cur["watermark"] and not a["watermark"])
            if better:
                if cur["watermark"]:
                    notes.append("the copy on file was stamped '%s' on every page and was replaced"
                                 % cur["watermark"])
                elif fragment or a["pages"] > cur["pages"]:
                    notes.append("the copy on file was %d page%s of a %d-page publication"
                                 % (cur["pages"], "" if cur["pages"] == 1 else "s", a["pages"]))
                notes.append(note)
                best, cur = alt, a

    if not cur["searchable"]:
        got, note = ocr(best, pub)
        if note:
            notes.append(note)
            best, cur = got, assess(got, pub)

    if cur["watermark"]:
        notes.append("STILL STAMPED '%s': this copy cannot be filed as it is." % cur["watermark"])
    if notes:
        _cache_put(pub, blob, best, notes)
    return best, notes
